import { h, config, pct, fmtDate, addChildren } from '../util.js';
import { store } from '../store.js';

const CARDS = [
  ['diagnostic', 'Диагностика', '20 вопросов — ориентировочная зона и слабые темы.'],
  ['grammar', 'Грамматика', 'Падежи, глагол, ступени, числительные, предлоги. Проверка сразу.'],
  ['vocab', 'Словарь', 'Карточки по школьным темам с интервальным повторением.'],
  ['reading', 'Чтение', 'Тексты и вопросы: выбор, верно/неверно, соответствие.'],
  ['listening', 'Аудирование', 'Озвучка синтезом речи (et-EE) и запасной вариант.'],
  ['writing', 'Письмо', 'Таймер, счётчик слов, чек-лист и список связок.'],
  ['speaking', 'Говорение', 'Карточки для пары, запись себя, самооценка.'],
  ['mock', 'Пробный экзамен', 'Все части подряд на таймере, ввод с клавиатуры.'],
  ['progress', 'Прогресс', 'Сводка по темам, слабые места, сброс.'],
];

export default {
  title: 'Главная',
  async mount(root) {
    const fmt = await config('exam-format');
    const diag = store.getDiag();
    const answers = Object.values(store.state.answers);
    const ok = answers.filter((a) => a.ok).length;
    addChildren(root, 
      h('h1', null, 'Подготовка к экзамену по эстонскому (B1)'),
      h('p', { class: 'lead' }, 'Тренажёр для учеников 8–9 классов: язык заданий — эстонский, объяснения — русский. Работает на телефоне и компьютере, без регистрации.'),
      h('div', { class: 'notice' },
        h('strong', null, 'Важно. '),
        'Это неофициальный учебный сайт. Результаты в тренажёре — ориентировочные и не предсказывают оценку на экзамене. ',
        'Формат экзамена (длительность частей, число заданий, баллы) в тренажёре заменён тренировочными значениями — ',
        h('strong', null, 'проверьте актуальный формат на '), h('a', { href: fmt.check_at, rel: 'noopener' }, 'harno.ee'), '.'),
      h('section', { 'aria-labelledby': 'start-h' },
        h('h2', { id: 'start-h' }, 'С чего начать'),
        h('ol', null,
          h('li', null, 'Пройдите ', h('a', { href: '#/diagnostic' }, 'диагностику'), ' — узнаете слабые темы.'),
          h('li', null, 'Тренируйте слабые темы в ', h('a', { href: '#/grammar' }, 'грамматике'), ' и ', h('a', { href: '#/vocab' }, 'словаре'), ' по 10–15 минут в день.'),
          h('li', null, 'Раз в неделю пробуйте чтение, аудирование, письмо и говорение.'),
          h('li', null, 'Ближе к экзамену сделайте ', h('a', { href: '#/mock' }, 'пробный экзамен'), '.'))),
      answers.length
        ? h('p', { class: 'muted' }, `Ваш прогресс: отвечено на ${answers.length} вопросов, верно в последний раз — ${ok} (${pct(ok, answers.length)} %).` + (diag ? ` Последняя диагностика: ${fmtDate(diag.ts)}.` : ''))
        : h('p', { class: 'muted' }, 'Пока нет ответов — самое время начать.'),
      h('div', { class: 'grid' }, CARDS.map(([id, t, d]) =>
        h('a', { class: 'card link-card', href: `#/${id}` }, h('h3', null, t), h('p', { class: 'muted' }, d)))),
      h('p', { class: 'notice privacy' }, h('strong', null, 'Приватность: '), 'аккаунтов, аналитики и трекеров нет. Прогресс хранится только в вашем браузере. Записи голоса не покидают вашу вкладку.')
    );
  },
};
